test('stale city and photo edits preserve newer albums and never resurrect deleted photos', async ({ page, context }) => {
  await page.goto('./#/trips/trip_vietnam')
  await page.getByRole('button', { name: 'Edit city dates & details', exact: true }).click()
  const other = await context.newPage()
  await other.goto('./#/trips/trip_vietnam')
  await place(other, 'Concurrent album', 'sight', '21.03')
  await other.locator('.place-list').getByRole('button', { name: /Concurrent album/ }).click()
  await other.locator('.upload-album input').setInputFiles({ name: 'race.png', mimeType: 'image/png', buffer: pixel })
  await expect(other.locator('.album-tile')).toHaveCount(1)
  await page.getByRole('button', { name: 'Save city', exact: true }).click()
  await page.reload()
  await page.locator('.place-list').getByRole('button', { name: /Concurrent album/ }).click()
  await expect(page.locator('.album-tile')).toHaveCount(1)
  for (const tab of [page, other]) await tab.locator('.album-tile').click()
  await page.getByLabel('Caption', { exact: true }).fill('New caption survives')
  await page.getByLabel('Photo date', { exact: true }).focus()
  await page.getByRole('button', { name: 'Close slideshow' }).click()
  // The stale tab must change only favourite, not overwrite the new caption.
  await other.getByRole('button', { name: 'Favourite', exact: true }).click()
  await expect(other.getByRole('button', { name: 'Favourite', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await page.locator('.place-list').getByRole('button', { name: /Concurrent album/ }).click()
  await page.locator('.album-tile').click()
  await expect(page.getByLabel('Caption', { exact: true })).toHaveValue('New caption survives')
  await expect(page.getByRole('button', { name: 'Favourite', exact: true })).toHaveAttribute('aria-pressed', 'true')
  page.on('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Remove photo from album' }).click()
  await expect(page.locator('.album-tile')).toHaveCount(0)
  await other.getByLabel('Caption', { exact: true }).fill('Must not resurrect')
  await other.getByLabel('Photo date', { exact: true }).focus()
  await expect(other.getByRole('dialog').getByRole('alert')).toContainText('Photo changes were not saved')
  await page.reload()
  await page.locator('.place-list').getByRole('button', { name: /Concurrent album/ }).click()
  await expect(page.locator('.album-tile')).toHaveCount(0)
})
